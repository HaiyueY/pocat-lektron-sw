#!/usr/bin/env python3
"""Generate src/subsystems/adcs/adcs_igrf14_coeffs.h from the IAGA IGRF-14 table.

Only the 2025.0 main-field coefficients (n <= 13) and the 2025-2030 secular
variation (n <= 8) are emitted; the flight model never needs the historical
DGRF columns. The square roots of the Legendre recursion are emitted as
tables too, so the on-board synthesis needs no sqrt per term (soft double
on the Cortex-M4).

Usage (from the repository root):
    python3 scripts/adcs/gen_igrf14_coeffs.py \
        scripts/adcs/igrf14coeffs.txt src/subsystems/adcs/adcs_igrf14_coeffs.h

Input source: https://www.ngdc.noaa.gov/IAGA/vmod/coeffs/igrf14coeffs.txt
"""

import hashlib
import math
import sys

SOURCE_URL = "https://www.ngdc.noaa.gov/IAGA/vmod/coeffs/igrf14coeffs.txt"
EPOCH_COLUMN = "2025.0"
NMAX = 13
SV_NMAX = 8


def index(n, m):
    """Packed index k(n, m) = n(n+1)/2 + m - 1 (n >= 1, 0 <= m <= n)."""
    return n * (n + 1) // 2 + m - 1


def parse(path):
    header = None
    g = {}
    h = {}
    gsv = {}
    hsv = {}
    with open(path, encoding="ascii") as f:
        for line in f:
            fields = line.split()
            if not fields or fields[0].startswith("#") or fields[0] == "c/s":
                continue
            if fields[0] == "g/h":
                header = fields
                continue
            if header is None:
                raise ValueError("data row before the 'g/h n m' header")
            col = header.index(EPOCH_COLUMN)
            kind, n, m = fields[0], int(fields[1]), int(fields[2])
            main = float(fields[col])
            sv = float(fields[-1])
            if kind == "g":
                g[(n, m)], gsv[(n, m)] = main, sv
            elif kind == "h":
                h[(n, m)], hsv[(n, m)] = main, sv
            else:
                raise ValueError("unexpected row: " + line)
    return g, h, gsv, hsv


def table(name, values, nmax, ncoef):
    out = [0.0] * ncoef
    for n in range(1, nmax + 1):
        for m in range(0, n + 1):
            out[index(n, m)] = values.get((n, m), 0.0)
    lines = ["static const float %s[%d] = {" % (name, ncoef)]
    for n in range(1, nmax + 1):
        row = ", ".join("%.2ff" % out[index(n, m)] for m in range(0, n + 1))
        lines.append("    /* n=%2d */ %s," % (n, row))
    lines.append("};")
    return "\n".join(lines)


def double_table(name, values, comment):
    lines = ["/** %s */" % comment,
             "static const double %s[%d] = {" % (name, len(values))]
    for i in range(0, len(values), 4):
        lines.append("    " + ", ".join("%.17g" % v for v in values[i:i + 4]) + ",")
    lines.append("};")
    return "\n".join(lines)


def recursion_tables(nmax, ncoef):
    """Constants of the Schmidt semi-normalised recursion, see adcs_igrf.c."""
    k2 = [0.0] * ncoef
    k3 = [0.0] * ncoef
    for n in range(1, nmax + 1):
        for m in range(0, n):
            k2[index(n, m)] = math.sqrt((n - 1) ** 2 - m ** 2)
            k3[index(n, m)] = 1.0 / math.sqrt(n ** 2 - m ** 2)
    pmm = [1.0, 1.0] + [math.sqrt((2 * m - 1) / (2 * m)) for m in range(2, nmax + 1)]
    return k2, k3, pmm


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    src, dst = sys.argv[1], sys.argv[2]
    with open(src, "rb") as f:
        sha256 = hashlib.sha256(f.read()).hexdigest()
    g, h, gsv, hsv = parse(src)

    # SV is only defined up to n = 8; anything above must be zero.
    for key, val in list(gsv.items()) + list(hsv.items()):
        if key[0] > SV_NMAX and val != 0.0:
            raise ValueError("non-zero SV above n=%d: %r" % (SV_NMAX, key))

    ncoef = index(NMAX, NMAX) + 1
    sv_ncoef = index(SV_NMAX, SV_NMAX) + 1
    k2, k3, pmm = recursion_tables(NMAX, ncoef)

    text = f"""/**
 * @file adcs_igrf14_coeffs.h
 * @brief IGRF-14 Gauss coefficients, epoch {EPOCH_COLUMN} — GENERATED, DO NOT EDIT.
 *
 * Generated by scripts/adcs/gen_igrf14_coeffs.py
 *   source: {SOURCE_URL}
 *   sha256: {sha256}
 *
 * Schmidt semi-normalised coefficients in nT (main field) and nT/yr
 * (secular variation, valid 2025.0–2030.0). Packed index
 * k(n, m) = n(n+1)/2 + m − 1 for 1 ≤ n, 0 ≤ m ≤ n; h(n, 0) = 0.
 * Private to adcs_igrf.c.
 */

#ifndef ADCS_IGRF14_COEFFS_H
#define ADCS_IGRF14_COEFFS_H

#define IGRF14_EPOCH        {EPOCH_COLUMN}
#define IGRF14_VALID_END    2030.0
#define IGRF14_NMAX         {NMAX}
#define IGRF14_SV_NMAX      {SV_NMAX}
#define IGRF14_NCOEF        {ncoef}
#define IGRF14_SV_NCOEF     {sv_ncoef}

{table("igrf14_g", g, NMAX, ncoef)}

{table("igrf14_h", h, NMAX, ncoef)}

{table("igrf14_gsv", gsv, SV_NMAX, sv_ncoef)}

{table("igrf14_hsv", hsv, SV_NMAX, sv_ncoef)}

{double_table("igrf14_k2", k2, "sqrt((n-1)^2 - m^2) at k(n, m), n > m (0 on the diagonal)")}

{double_table("igrf14_k3", k3, "1 / sqrt(n^2 - m^2) at k(n, m), n > m (0 on the diagonal)")}

{double_table("igrf14_pmm", pmm, "sqrt((2m-1)/(2m)) for m >= 2; 1 for m = 0, 1 (P_1^1 = sin(theta))")}

#endif /* ADCS_IGRF14_COEFFS_H */
"""
    with open(dst, "w", encoding="utf-8") as f:
        f.write(text)


if __name__ == "__main__":
    main()
